"""Extract unchanged graphical engine/assets from the user-provided Origami bundle."""
from pathlib import Path
import hashlib
import json
import sys
SOURCE = Path('vendor/origami_weather/origami-weather.js')
TARGET = Path('src/origami-engine.js')
MANIFEST = Path('src/origami-source.json')
s = SOURCE.read_text()
def between(a, b):
    return s[s.index(a):s.index(b, s.index(a))]
blocks = {
    'assets': between('// src/image-assets.js', '// src/origami-weather.js'),
    'palettes': between('var _SKY_FILTERS =', 'var WEATHER_ATTR_ICONS ='),
    'engine': between('var WeatherEffects =', 'var ESCAPE_MAP ='),
    'sun_palette': between('  static _sunPalette(', '  _applyMoonPhase('),
    'moon_geometry': between('  static _moonPhase(', '  _warnMissingSun('),
}
css = between('            .sky-haze {', '            #card-root.has-default-bg #default-bg')
css = '\n'.join(line for line in css.splitlines() if '#card-root' not in line)
celestial = between('            #sun-moon .sun-glow,', '            #sun-rays {')
celestial = '\n'.join(line for line in celestial.splitlines() if '#card-root' not in line)
celestial = celestial.replace('#sun-moon ', '').replace('#sun-moon.is-astro-night', '.is-astro-night').replace('#sun-moon:not(.is-astro-night)', '.is-astro-day')
# These styles and the original texture are applied to the fullscreen adapter's orbs.
header = '/** Vendored unchanged rendering engine and image assets from Origami Weather.\n * Source: www/community/origami_weather/origami-weather.js.\n * Generated by tests/dashboard_weather/vendor_origami.py; no card/editor runtime.\n */\n'
body = header + '\n'.join(blocks[k] for k in ['assets','palettes','engine'])
body += '\nclass OriginalAstronomy {\n' + blocks['sun_palette'] + blocks['moon_geometry'] + '\n}\n'
body += '\nconst SKY_STYLES = ' + json.dumps(css + '\n' + celestial) + ';\n'
body += '''\nlet ready;
function assetsReady() {
  return ready ||= Promise.all([CLOUD_SPRITE,CLOUD_SOFT,BIRD_SHEET,BALLOON_SHEET,PLANE_SHEET,MOON_SURFACE].map(src => new Promise((resolve,reject) => {
    const img = new Image(); img.onload = () => resolve(); img.onerror = () => reject(new Error('Origami sky asset failed to load')); img.src = src;
  })));
}
export {WeatherEffects, WEATHER_TUNING, _weatherTuning, _SKY_FILTERS, _DARK_THEME_FILTER, _HAZE_PALETTE, _HAZE_TUNING,
  MOON_SURFACE, SUN_PALETTE, OriginalAstronomy, SKY_STYLES, assetsReady};
'''
manifest = {'source': 'www/community/origami_weather/origami-weather.js', 'sha256': hashlib.sha256(s.encode()).hexdigest(),
            'blocks': {k: hashlib.sha256(v.encode()).hexdigest() for k,v in blocks.items()}}
if '--write' in sys.argv:
    TARGET.write_text(body)
    MANIFEST.write_text(json.dumps(manifest,indent=2)+'\n')
else:
    assert TARGET.read_text() == body, 'Vendored engine differs from original extraction'
    assert json.loads(MANIFEST.read_text()) == manifest, 'Original snapshot changed; review before regenerating'
    print('Original Origami assets, renderer and moon geometry match source exactly')
